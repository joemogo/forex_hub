#!/usr/bin/env python3
"""MOGO-011 Step 2 -- retry policy, attempt semantics, backoff and eligibility.

Pure stdlib (unittest). Fully offline, deterministic, repeatable. Every test
that touches state uses a tempfile state root; no test sleeps.

WHY NOTHING SLEEPS, AND WHY THAT IS NOT A SHORTCUT
    The runtime never waits: `run` is one-shot and releases whatever is
    eligible now. A test that wants to observe a release advances an INJECTED
    clock and calls `run` again. The eligibility comparison the runtime makes
    is identical either way -- what the injection removes is the waiting, not
    the check. `test_a_retry_is_not_released_before_its_eligibility` proves the
    rule bites by leaving the clock alone and asserting nothing is released.

Run with:
    python3 -m unittest tests.platform.test_runtime_retry -v
"""

