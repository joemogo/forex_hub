class TestEligibility(unittest.TestCase):
    def test_eligibility_is_inclusive_at_the_boundary(self):
        self.assertFalse(retry.is_eligible(1000, 999))
        self.assertTrue(retry.is_eligible(1000, 1000))
        self.assertTrue(retry.is_eligible(1000, 1001))

    def test_a_zero_backoff_is_eligible_at_once(self):
        now = 1_700_000_000_000
        self.assertTrue(retry.is_eligible(retry.next_eligible_at_ms(now, 0), now))

    def test_iso8601_lexical_order_matches_chronological_order(self):
        """The SQL filter compares strings; the Python predicate compares
        integers. If the two orders could disagree, a retry could be released
        by one and withheld by the other."""
        stamps = ["1999-12-31T23:59:59.999Z", "2000-01-01T00:00:00.000Z",
                  "2026-08-08T11:59:59.999Z", "2026-08-08T12:00:00.000Z",
                  "2026-08-08T12:00:00.001Z", "2026-12-31T23:59:59.999Z",
                  "2027-01-01T00:00:00.000Z"]
        by_string = sorted(stamps)
        by_instant = sorted(stamps, key=lambda s: clock_module.parse_iso8601_ms(s))
        self.assertEqual(by_string, by_instant)
        for earlier, later in zip(stamps, stamps[1:]):
            with self.subTest(pair=(earlier, later)):
                self.assertEqual(
                    earlier < later,
                    clock_module.parse_iso8601_ms(earlier)
                    < clock_module.parse_iso8601_ms(later))


class TestClockDiscipline(unittest.TestCase):
    def test_round_trip_is_exact_at_millisecond_precision(self):
        for stamp in ("1970-01-01T00:00:00.000Z", "2026-08-08T12:00:00.001Z",
                      "2026-12-31T23:59:59.999Z"):
            with self.subTest(stamp=stamp):
                self.assertEqual(
                    clock_module.format_ms(clock_module.parse_iso8601_ms(stamp)),
                    stamp)

    def test_a_manual_clock_advances_only_when_told(self):
        clock = clock_module.ManualClock("2026-08-08T12:00:00.000Z")
        self.assertEqual(clock.now_iso(), "2026-08-08T12:00:00.000Z")
        self.assertEqual(clock.now_iso(), "2026-08-08T12:00:00.000Z")
        clock.advance_ms(1500)
        self.assertEqual(clock.now_iso(), "2026-08-08T12:00:01.500Z")

    def test_a_manual_clock_refuses_to_advance_backwards(self):
        clock = clock_module.ManualClock("2026-08-08T12:00:00.000Z")
        with self.assertRaises(runtime_errors.ClockRollbackError):
            clock.advance_ms(-1)

    def test_the_monotonic_floor_accepts_equality_and_refuses_the_past(self):
        floor = clock_module.MonotonicFloor()
        floor.observe("2026-08-08T12:00:00.005Z")
        # Nine events inside one millisecond is normal and must stay legal.
        floor.check("2026-08-08T12:00:00.005Z")
        floor.check("2026-08-08T12:00:00.006Z")
        with self.assertRaises(runtime_errors.ClockRollbackError):
            floor.check("2026-08-08T12:00:00.004Z")

    def test_no_skew_tolerance_is_granted(self):
        floor = clock_module.MonotonicFloor()
        floor.observe("2026-08-08T12:00:00.100Z")
        with self.assertRaises(runtime_errors.ClockRollbackError):
            floor.check("2026-08-08T12:00:00.099Z")   # one millisecond early

    def test_a_naive_datetime_is_refused(self):
        import datetime as datetime_module
        with self.assertRaises(runtime_errors.ContractValidationError):
            clock_module.format_iso8601_ms(datetime_module.datetime(2026, 8, 8))


class RuntimeRetryCase(unittest.TestCase):
    """End-to-end retry behaviour against a real state root and a real log."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.paths = paths_module.RuntimePaths(os.path.join(self._tmp.name, "state"))
        self.clock = clock_module.ManualClock("2026-08-08T12:00:00.000Z")
        self.runtime = orchestrator_module.Orchestrator(
            paths=self.paths, clock=self.clock).open()
        self.runtime.register_builtin_capabilities()

    def tearDown(self):
        self.runtime.close()
        self._tmp.cleanup()

    def submit_retry_task(self, fail_until, note="retry", backoff_base_ms=None):
        """Submit a fail-then-succeed task, optionally with a non-zero backoff.

        The backoff override is applied to the TASK's recorded policy, which is
        exactly where the runtime reads it from -- so this exercises the real
        release path rather than a parallel one.
        """
        envelope, payload = cli_module.build_retry_demo_command(fail_until, note)
        outcome = self.runtime.submit(envelope, payload)
        if backoff_base_ms is not None:
            policy = json.loads(self.runtime.connection.execute(
                "SELECT retry_policy FROM tasks WHERE task_id = ?",
                (outcome.task_id,)).fetchone()[0])
            policy["backoffBaseMs"] = backoff_base_ms
            with self.runtime.connection:
                self.runtime.connection.execute(
                    "UPDATE tasks SET retry_policy = ? WHERE task_id = ?",
                    (json.dumps(policy, sort_keys=True), outcome.task_id))
        return outcome

    def task(self, task_id):
        return self.runtime.connection.execute(
            "SELECT * FROM tasks WHERE task_id = ?", (task_id,)).fetchone()

    def event_types(self, task_id):
        return [row[0] for row in self.runtime.connection.execute(
            "SELECT event_type FROM event_index WHERE task_id = ? "
            "ORDER BY log_sequence", (task_id,))]


class TestRetryEndToEnd(RuntimeRetryCase):
    def test_a_retryable_failure_is_retried_and_then_succeeds(self):
        outcome = self.submit_retry_task(1)
        self.runtime.run_once()
        row = self.task(outcome.task_id)
        self.assertEqual(row["state"], "succeeded")
        self.assertEqual(row["attempt"], 2)
        self.assertEqual(row["terminal"], 1)

    def test_retry_event_ordering_is_exact(self):
        outcome = self.submit_retry_task(1)
        self.runtime.run_once()
        types = self.event_types(outcome.task_id)
        expected = ["TaskRequested", "TaskPolicyCheckRequested", "PolicyEvaluated",
                    "TaskClaimed", "TaskStarted", "TaskFailed",
                    "TaskRetryScheduled", "TaskRetryReleased", "TaskClaimed",
                    "TaskStarted", "TaskSucceeded"]
        self.assertEqual(types, expected)

    def test_attempt_increments_exactly_once_per_execution(self):
        outcome = self.submit_retry_task(2)
        self.runtime.run_once()
        row = self.task(outcome.task_id)
        starts = self.event_types(outcome.task_id).count("TaskStarted")
        self.assertEqual(row["attempt"], starts)
        self.assertEqual(row["attempt"], 3)

    def test_replaying_task_started_does_not_increment_the_attempt(self):
        from mogo_platform.runtime import projection
        outcome = self.submit_retry_task(1)
        self.runtime.run_once()
        before = self.task(outcome.task_id)["attempt"]
        # Replay the WHOLE log from the beginning against the live index.
        projection.replay(self.runtime.connection, self.runtime.log,
                          from_log_sequence=0)
        self.assertEqual(self.task(outcome.task_id)["attempt"], before)

    def test_attempt_is_written_by_exactly_one_sql_statement_in_the_runtime(self):
        """A double increment cannot hide anywhere, because nothing else in the
        runtime touches tasks.attempt.

        AST, not a text scan: a comment explaining the increment is prose, and
        a test that counted prose would fail for the wrong reason -- and could
        be "fixed" by deleting the explanation.
        """
        import ast
        runtime_dir = os.path.join(SRC_DIR, "mogo_platform", "runtime")
        increments, assignments = [], []
        for root, _dirs, files in os.walk(runtime_dir):
            for name in sorted(files):
                if not name.endswith(".py"):
                    continue
                path = os.path.join(root, name)
                with open(path, "r", encoding="utf-8") as handle:
                    tree = ast.parse(handle.read(), filename=path)
                for node in ast.walk(tree):
                    if not (isinstance(node, ast.Constant)
                            and isinstance(node.value, str)):
                        continue
                    if "attempt + 1" in node.value:
                        increments.append((name, node.lineno, node.value))
                    upper = node.value.upper()
                    if "SET ATTEMPT" in upper or "ATTEMPT =" in upper:
                        assignments.append((name, node.lineno, node.value))
        self.assertEqual(len(increments), 1, increments)
        self.assertEqual(increments[0][0], "projection.py")
        # No other statement assigns the column at all.
        self.assertEqual(assignments, [])

    def test_the_idempotency_key_is_identical_across_every_attempt(self):
        outcome = self.submit_retry_task(2)
        before = self.task(outcome.task_id)["idempotency_key"]
        self.runtime.run_once()
        after = self.task(outcome.task_id)
        self.assertEqual(after["attempt"], 3)
        self.assertEqual(after["idempotency_key"], before)

    def test_the_execution_context_is_not_part_of_the_idempotency_key(self):
        """The key is derived from the semantic payload alone.

        `ids.idempotency_key` rejects an undeclared part, so an attempt number
        cannot be smuggled into a key even by mistake -- asserted directly.
        """
        parts = {"inputHash": "a" * 64, "transformationId": "XF|x",
                 "transformationVersion": "1.0.0"}
        base = ids.idempotency_key("transformation", parts)
        self.assertEqual(ids.idempotency_key("transformation", dict(parts)), base)
        with self.assertRaises(contract_errors.IdentifierError):
            ids.idempotency_key("transformation", dict(parts, attempt=2))

    def test_retry_scheduling_is_reconstructable_from_the_log_alone(self):
        outcome = self.submit_retry_task(1)
        self.runtime.run_once()
        scheduled = self._payloads(outcome.task_id, "TaskRetryScheduled")
        self.assertEqual(len(scheduled), 1)
        payload = scheduled[0]
        for field in ("attempt", "attemptLimit", "errorClass", "decisionReason",
                      "backoffMs", "eligibleAtUtc", "scheduledAtUtc",
                      "retryPolicy"):
            self.assertIn(field, payload)
        self.assertEqual(
            sorted(payload["retryPolicy"]),
            ["backoffBaseMs", "backoffCapMs", "backoffMultiplier", "jitterMs"])
        # The schedule is verifiable without knowing which build produced it.
        expected = retry.backoff_ms(payload["attempt"],
                                    dict(payload["retryPolicy"], attemptLimit=3))
        self.assertEqual(payload["backoffMs"], expected)

