class TestRetryabilityReadsOneTable(unittest.TestCase):
    def test_the_committed_table_matches_the_catalog(self):
        self.assertEqual(set(contract_errors.ERROR_CLASSES), set(CATALOG_SECTION_K))
        for name, (retryable, terminal, review) in CATALOG_SECTION_K.items():
            with self.subTest(error_class=name):
                record = contract_errors.ERROR_CLASSES[name]
                self.assertEqual(record["retryable"], retryable)
                self.assertEqual(record["terminal"], terminal)
                self.assertEqual(record["routesToReview"], review)

    def test_is_retryable_agrees_with_the_catalog_for_every_class(self):
        for name, (retryable, _t, _r) in CATALOG_SECTION_K.items():
            with self.subTest(error_class=name):
                self.assertEqual(retry.is_retryable(name), retryable)

    def test_no_error_class_name_is_hard_coded_as_a_retryable_literal(self):
        """The retry module must consult the table, never restate it.

        A second list of retryable class names is a second place to be wrong,
        and the two would drift silently. `policy_blocked` is the ONE permitted
        literal, because Constitution section 11 singles it out and the guard
        must work even if the table were mutated.
        """
        import inspect
        source = inspect.getsource(retry)
        for name in CATALOG_SECTION_K:
            if name == "policy_blocked":
                continue
            with self.subTest(error_class=name):
                self.assertNotIn('"%s"' % name, source)
                self.assertNotIn("'%s'" % name, source)

    def test_policy_blocked_is_not_retryable_in_the_contract_table(self):
        self.assertFalse(contract_errors.ERROR_CLASSES["policy_blocked"]["retryable"])


class TestClassifyFailure(unittest.TestCase):
    def test_a_retryable_failure_schedules_a_retry(self):
        for name in ("transient", "rate_limited", "dependency_unavailable"):
            with self.subTest(error_class=name):
                decision = retry.classify_failure(name, 1, 3)
                self.assertTrue(decision.retry)
                self.assertEqual(decision.reason, "retryable_within_attempt_limit")

    def test_a_non_retryable_failure_does_not_schedule_a_retry(self):
        for name in ("authentication", "not_found", "validation",
                     "deterministic_processing", "corrupted_input", "permanent"):
            with self.subTest(error_class=name):
                decision = retry.classify_failure(name, 1, 3)
                self.assertFalse(decision.retry)
                self.assertEqual(decision.reason, "non_retryable_error_class")

    def test_policy_blocked_never_retries(self):
        for attempt in range(0, 12):
            with self.subTest(attempt=attempt):
                decision = retry.classify_failure("policy_blocked", attempt, 10)
                self.assertFalse(decision.retry)
                self.assertEqual(decision.reason, "policy_denial_never_retried")

    def test_policy_denial_is_refused_even_if_the_table_says_retryable(self):
        """Guard 2, proved independent of guard 1.

        The table is monkeypatched to claim a policy denial is retryable. The
        decision must still refuse, because the guard is checked BEFORE the
        table is consulted. Constitution section 11: retrying a policy denial
        is an attempt to launder it, so one guard is not enough.
        """
        original = contract_errors.ERROR_CLASSES
        patched = dict(original)
        patched["policy_blocked"] = {"retryable": True, "terminal": False,
                                     "routesToReview": False}
        contract_errors.ERROR_CLASSES = patched
        try:
            decision = retry.classify_failure("policy_blocked", 1, 3)
            self.assertFalse(decision.retry)
            self.assertEqual(decision.reason, "policy_denial_never_retried")
        finally:
            contract_errors.ERROR_CLASSES = original
        self.assertIs(contract_errors.ERROR_CLASSES, original)

    def test_an_unknown_error_class_is_not_retryable(self):
        for name in ("", "not_a_class", "TRANSIENT", None, "transient "):
            with self.subTest(error_class=name):
                decision = retry.classify_failure(name, 1, 3)
                self.assertFalse(decision.retry)
                self.assertEqual(decision.reason, "unknown_error_class")

    def test_a_review_routing_class_has_nowhere_legal_to_go(self):
        for name in ("source_mutated", "human_review_required"):
            with self.subTest(error_class=name):
                self.assertTrue(retry.requires_review_gate(name))
                decision = retry.classify_failure(name, 1, 3)
                self.assertFalse(decision.retry)
                self.assertEqual(decision.reason, "requires_review_no_gate")

    def test_no_failed_to_awaiting_review_edge_exists_in_the_contract(self):
        """The finding decision B-3 rests on, asserted against the contract."""
        from mogo_platform.contracts import task_states
        self.assertEqual(task_states.legal_successors("failed"),
                         ("cancelled", "dead_lettered", "retry_scheduled"))
        self.assertNotIn("awaiting_review", task_states.legal_successors("failed"))

    def test_the_attempt_limit_is_enforced_exactly(self):
        # attemptLimit counts TOTAL attempts, not retries: limit 3 permits
        # 3 executions, i.e. the first plus at most 2 retries.
        cases = {(1, 3): True, (2, 3): True, (3, 3): False, (4, 3): False,
                 (1, 1): False, (1, 2): True, (2, 2): False,
                 (9, 10): True, (10, 10): False}
        for (attempt, limit), should_retry in cases.items():
            with self.subTest(attempt=attempt, limit=limit):
                decision = retry.classify_failure("transient", attempt, limit)
                self.assertEqual(decision.retry, should_retry)
                if not should_retry:
                    self.assertEqual(decision.reason, "attempts_exhausted")

    def test_every_error_class_reaches_the_expected_terminal_reason(self):
        expected = {
            "transient": None, "rate_limited": None, "dependency_unavailable": None,
            "authentication": "non_retryable_error_class",
            "policy_blocked": "policy_denial_never_retried",
            "not_found": "non_retryable_error_class",
            "validation": "non_retryable_error_class",
            "deterministic_processing": "non_retryable_error_class",
            "corrupted_input": "non_retryable_error_class",
            "permanent": "non_retryable_error_class",
            "source_mutated": "requires_review_no_gate",
            "human_review_required": "requires_review_no_gate",
            "invented_class": "unknown_error_class",
        }
        self.assertEqual(len(expected), 13)
        for name, reason in expected.items():
            with self.subTest(error_class=name):
                self.assertEqual(retry.dead_letter_reason(name, 1, 3), reason)

    def test_every_dead_letter_reason_is_declared(self):
        self.assertEqual(len(retry.DEAD_LETTER_REASONS), 5)
        for name in CATALOG_SECTION_K:
            reason = retry.dead_letter_reason(name, 99, 3)
            with self.subTest(error_class=name):
                self.assertIn(reason, retry.DEAD_LETTER_REASONS)


class TestBackoff(unittest.TestCase):
    def test_backoff_matches_the_independently_transcribed_table(self):
        for attempt, expected in EXPECTED_BACKOFF_TABLE.items():
            with self.subTest(attempt=attempt):
                self.assertEqual(retry.backoff_ms(attempt, DEFAULT_POLICY), expected)

    def test_backoff_uses_integer_arithmetic_only(self):
        for attempt in range(1, 21):
            value = retry.backoff_ms(attempt, DEFAULT_POLICY)
            with self.subTest(attempt=attempt):
                self.assertIsInstance(value, int)
                self.assertNotIsInstance(value, float)

    def test_backoff_is_identical_for_identical_inputs(self):
        for attempt in range(1, 11):
            values = {retry.backoff_ms(attempt, DEFAULT_POLICY)
                      for _ in range(1000)}
            with self.subTest(attempt=attempt):
                self.assertEqual(len(values), 1)

    def test_backoff_is_capped(self):
        policy = dict(DEFAULT_POLICY, backoffCapMs=5000)
        for attempt in range(1, 15):
            with self.subTest(attempt=attempt):
                self.assertLessEqual(retry.backoff_ms(attempt, policy), 5000)

    def test_a_multiplier_of_one_is_constant_backoff(self):
        policy = dict(DEFAULT_POLICY, backoffMultiplier=1)
        for attempt in range(1, 10):
            with self.subTest(attempt=attempt):
                self.assertEqual(retry.backoff_ms(attempt, policy), 1000)

    def test_backoff_is_computed_for_a_one_based_attempt(self):
        for bad in (0, -1, True, 1.5, "1", None):
            with self.subTest(attempt=bad):
                with self.assertRaises(runtime_errors.RetryPolicyError):
                    retry.backoff_ms(bad, DEFAULT_POLICY)

    def test_jitter_is_zero_and_no_randomness_is_importable(self):
        self.assertEqual(retry.DEFAULT_RETRY_POLICY["jitterMs"], 0)
        with self.assertRaises(runtime_errors.RetryPolicyError):
            retry.validate_policy(dict(DEFAULT_POLICY, jitterMs=25))
        import inspect
        source = inspect.getsource(retry)
        self.assertNotIn("import random", source)
        self.assertNotIn("import secrets", source)

    def test_a_float_multiplier_is_refused_rather_than_coerced(self):
        for bad in (2.0, 1.5, "2", None, True):
            with self.subTest(multiplier=bad):
                with self.assertRaises(runtime_errors.RetryPolicyError):
                    retry.validate_policy(dict(DEFAULT_POLICY,
                                               backoffMultiplier=bad))

    def test_a_multiplier_below_one_is_refused(self):
        for bad in (0, -1):
            with self.subTest(multiplier=bad):
                with self.assertRaises(runtime_errors.RetryPolicyError):
                    retry.validate_policy(dict(DEFAULT_POLICY,
                                               backoffMultiplier=bad))

    def test_a_negative_policy_value_is_refused(self):
        for field in ("backoffBaseMs", "backoffCapMs", "jitterMs"):
            with self.subTest(field=field):
                with self.assertRaises(runtime_errors.RetryPolicyError):
                    retry.validate_policy(dict(DEFAULT_POLICY, **{field: -1}))


